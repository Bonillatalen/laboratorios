distancia = float(input("Ingrese la distancia en kilometros: "))
metros = distancia * 1000
centimetros = distancia * 100000
millas = distancia * 0.621371
print("La distancia en metros es:", metros, "m")
print("La distancia en centimetros es:", centimetros, "cm")
print("la distancia en millas es:",millas, "mi")